def _classify(keyword: str, industry: str) -> str:
    """关键词 + 行业 → 领域。行业优先，其次按关键词命中，默认通用。"""
    if industry and industry in DOMAIN_DEFS:
        return industry
    for dom, kws in DOMAIN_KEYWORDS.items():
        if any(k in keyword for k in kws):
            return dom
    return "通用"


def _clean(phenomenon: str) -> str:
    """轻微清洗：去掉首尾空白与被热议标记造成的句末标点。"""
    return phenomenon.strip().rstrip("！!?？。. ")


def propose(keyword: str, industry: str = "") -> dict:
    """给定热点关键词（现象），产出 3 个争点选题备选标题 + 三要素检验。

    返回结构（纯本地确定性，无网络 / 无大模型）：
      {
        "ok": True,
        "phenomenon": str,
        "domain": str,
        "three_elements": {...},
        "titles": [ {type, title, note}, x3 ],
        "method": str,
      }
    """
    phenomenon = _clean(keyword)
    if not phenomenon:
        return {"ok": False, "error": "关键词为空"}

    domain = _classify(phenomenon, industry)
    lib = DOMAIN_DEFS[domain]
    defs = lib["defs"]
    popular = lib["popular"]

    # ── 三要素检验（对应 SKILL.md「什么才算选题」） ──
    three_elements = {
        "common_fact": f"「{phenomenon}」这件事本身真实发生（或真实存在热议），各方都不否认。",
        "different_interpretations": [
            f"一方认为是{defs[0]}",
            f"另一方认为是{defs[1]}" + (f"，甚至还有第 {len(defs)} 种说法" if len(defs) > 2 else ""),
        ],
        "must_judge": f"「{phenomenon}」到底该被定义成什么？—— 这才是观众被迫站队的核心争点。",
    }

    # ── 两个争点层展开 ──
    # 事实争点：质疑被热议的"既定事实 / 流行说法"，把结论打回成问题
    fact_title = f"{phenomenon}，真的{popular}吗？"
    # 定义争点：穷举候选定义，一个候选定义 = 一个选题
    def_titles = [f"{phenomenon}，真的是{d}吗？" for d in defs[:2]]

    titles = [
        {
            "type": "事实争点",
            "title": fact_title,
            "note": "质疑被热议的「既定事实 / 流行说法」，把结论打回成问题",
        },
        {
            "type": "定义争点",
            "title": def_titles[0],
            "note": f"把现象重新定义成「{defs[0]}」，引导观众带着判断看完",
        },
        {
            "type": "定义争点",
            "title": def_titles[1],
            "note": f"把现象重新定义成「{defs[1]}」，提供第二个可站队的立场",
        },
    ]

    return {
        "ok": True,
        "phenomenon": phenomenon,
        "domain": domain,
        "three_elements": three_elements,
        "titles": titles,
        "method": "stasis 争点选题法（亚里士多德修辞学）· 确定性生成，无需大模型 Key / 本地 Ollama",
    }
